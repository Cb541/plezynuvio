var lru = NuvioPreviewLRU<String>(maxCount: 3, maxBytes: 9)
lru.put("a", key: 12, cost: 3)
lru.put("b", key: 24, cost: 3)
lru.put("c", key: 36, cost: 3)
assert(lru.get(12) == "a")
lru.put("d", key: 48, cost: 3)
assert(!lru.contains(24) && lru.keys == Set([12, 36, 48]))
lru.put("large", key: 60, cost: 7)
assert(lru.keys == Set([60]) && lru.bytes == 7)
lru.put("oversized", key: 72, cost: 10)
assert(!lru.contains(72) && lru.bytes == 7)
lru.removeAll()
assert(lru.keys.isEmpty && lru.bytes == 0)
var jpeg = NuvioPreviewLRU<Int>(maxCount: 256, maxBytes: 24 * 1024 * 1024)
for i in 0..<300 { jpeg.put(i, key: i*12, cost: 4096) }
assert(jpeg.keys.count == 256 && !jpeg.contains(0) && jpeg.get(299*12) == 299)
print("On-demand preview cache: LRU hit, eviction, byte limits and session clear passed")
